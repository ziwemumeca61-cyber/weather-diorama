const R = 6371 // 地球半径 km
function haversine(lat1, lng1, lat2, lng2) {
  const rad = Math.PI / 180
  const dLat = (lat2 - lat1) * rad
  const dLng = (lng2 - lng1) * rad
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) * Math.sin(dLng / 2)
  return 2 * R * Math.asin(Math.min(1, Math.sqrt(a)))
}

/**
 * 找出最近的已注册城市。maxKm 内才算命中，否则返回 null
 * （在没有专属地标的地方，仍走程序化地标，不硬套一个不相干的城市）。
 */
export function nearestCity(lat, lng, maxKm) {
  const lim = maxKm || 120
  let best = null
  let bestD = Infinity
  for (const name in CITY_COORDS) {
    const c = CITY_COORDS[name]
    const d = haversine(lat, lng, c[0], c[1])
    if (d < bestD) {
      bestD = d
      best = name
    }
  }
  return bestD <= lim ? { name: best, km: bestD } : null
}
